// Capa de datos de ReportaCalle.
//
// - Si DATABASE_URL tiene una cadena real, se usa PostgreSQL (en producción: Supabase).
// - Si no, se usa SQLite en data/reportacalle.sqlite (paquete better-sqlite3).
// - Si ese paquete no se pudo instalar, se usa data/reportacalle.json.
//
// Puedes forzar el modo con DATA_BACKEND=postgres|sqlite|json|auto.
// El resto de la aplicación solo usa las funciones que devuelve crearDatos().

const fs = require('fs');
const path = require('path');
const { directorioDatos } = require('./config');
const { formatearFolio, esPendiente } = require('./util');


const INDICES = [
  'CREATE INDEX IF NOT EXISTS idx_reportes_estatus ON reportes (estatus)',
  'CREATE INDEX IF NOT EXISTS idx_reportes_categoria ON reportes (categoria)',
  'CREATE INDEX IF NOT EXISTS idx_fotos_reporte ON fotos (reporte_id)',
  'CREATE INDEX IF NOT EXISTS idx_envios_reporte ON envios (reporte_id)',
];

function crearCola() {
  let cadena = Promise.resolve();
  return function exclusivo(fn) {
    const corre = cadena.then(() => fn());
    cadena = corre.then(() => {}, () => {});
    return corre;
  };
}

function aPg(sql) {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
}

function presentar(fila, fotos, envios) {
  const num = (v) => (v == null || v === '' ? null : Number(v));
  return {
    id: fila.id,
    folio: fila.folio,
    categoria: fila.categoria,
    descripcion: fila.descripcion,
    lat: Number(fila.lat),
    lng: Number(fila.lng),
    anonimo: Boolean(fila.anonimo),
    contactoNombre: fila.contacto_nombre || null,
    contactoDato: fila.contacto_dato || null,
    estatus: fila.estatus,
    largoCm: num(fila.largo_cm),
    anchoCm: num(fila.ancho_cm),
    profundidadCm: num(fila.profundidad_cm),
    areaCm2: num(fila.area_cm2),
    recomendacion: fila.recomendacion || null,
    enviadoEn: fila.enviado_en || null,
    creadoEn: fila.creado_en,
    actualizadoEn: fila.actualizado_en,
    // `clave` es la ruta interna del archivo. Las rutas HTTP la quitan
    // antes de responder al navegador.
    fotos: (fotos || []).map((f) => ({
      id: f.id,
      origen: f.origen,
      url: f.url,
      clave: f.clave,
    })),
    envios: (envios || []).map((e) => ({
      id: e.id,
      folio: e.folio,
      destinatario: e.destinatario,
      fecha: e.fecha,
      estado: e.estado,
      error: e.error || null,
    })),
  };
}

function crearRepositorioSql({ motor, exclusivo, q, tx, cerrar, asegurarTablas }) {
  async function armar(consulta, filas) {
    if (!filas.length) return [];
    const ids = filas.map((f) => f.id);
    const marcas = ids.map(() => '?').join(',');
    const fotos = await consulta.all(
      `SELECT * FROM fotos WHERE reporte_id IN (${marcas}) ORDER BY id`,
      ids
    );
    const envios = await consulta.all(
      `SELECT * FROM envios WHERE reporte_id IN (${marcas}) ORDER BY id`,
      ids
    );
    return filas.map((fila) => presentar(
      fila,
      fotos.filter((f) => f.reporte_id === fila.id),
      envios.filter((e) => e.reporte_id === fila.id)
    ));
  }

  async function porFolio(folio) {
    return exclusivo(async () => {
      const filas = await q.all('SELECT * FROM reportes WHERE folio = ?', [folio]);
      if (!filas[0]) return null;
      return (await armar(q, filas))[0];
    });
  }

  return {
    motor,
    async preparar() {
      await asegurarTablas();
    },
    async ping() {
      const filas = await exclusivo(() => q.all('SELECT 1 AS ok', []));
      return filas.length === 1;
    },
    async cerrar() {
      await cerrar();
    },
    async crearReporte(datos, fotos) {
      const folio = await tx(async (consulta) => {
        const sec = await consulta.all(
          `INSERT INTO secuencias (nombre, valor) VALUES ('folio', 1)
           ON CONFLICT(nombre) DO UPDATE SET valor = secuencias.valor + 1
           RETURNING valor`,
          []
        );
        const nuevo = formatearFolio(sec[0].valor);
        const ahora = new Date().toISOString();
        const filas = await consulta.all(
          `INSERT INTO reportes (
             folio, categoria, descripcion, lat, lng, anonimo,
             contacto_nombre, contacto_dato, estatus, creado_en, actualizado_en
           ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, 'recibido', ?, ?)
           RETURNING id`,
          [
            nuevo,
            datos.categoria,
            datos.descripcion,
            datos.lat,
            datos.lng,
            datos.anonimo ? 1 : 0,
            datos.contactoNombre,
            datos.contactoDato,
            ahora,
            ahora,
          ]
        );
        const id = filas[0].id;
        for (const foto of fotos) {
          await consulta.run(
            `INSERT INTO fotos (reporte_id, origen, url, clave, creado_en)
             VALUES (?, ?, ?, ?, ?)`,
            [id, foto.origen, foto.url, foto.clave, ahora]
          );
        }
        return nuevo;
      });
      return porFolio(folio);
    },
    listar({ estatus, categoria } = {}) {
      return exclusivo(async () => {
        const where = [];
        const params = [];
        if (estatus) {
          where.push('estatus = ?');
          params.push(estatus);
        }
        if (categoria) {
          where.push('categoria = ?');
          params.push(categoria);
        }
        const sql = `SELECT * FROM reportes ${where.length ? `WHERE ${where.join(' AND ')}` : ''} ORDER BY id DESC`;
        const filas = await q.all(sql, params);
        return armar(q, filas);
      });
    },
    porFolio,
    async actualizar(folio, campos) {
      await tx(async (consulta) => {
        await consulta.run(
          `UPDATE reportes SET
             estatus = ?,
             largo_cm = ?,
             ancho_cm = ?,
             profundidad_cm = ?,
             area_cm2 = ?,
             recomendacion = ?,
             actualizado_en = ?
           WHERE folio = ?`,
          [
            campos.estatus,
            campos.largoCm,
            campos.anchoCm,
            campos.profundidadCm,
            campos.areaCm2,
            campos.recomendacion,
            new Date().toISOString(),
            folio,
          ]
        );
      });
      return porFolio(folio);
    },
    async agregarFotos(folio, fotos) {
      await tx(async (consulta) => {
        const filas = await consulta.all('SELECT id FROM reportes WHERE folio = ?', [folio]);
        if (!filas[0]) return;
        const ahora = new Date().toISOString();
        for (const foto of fotos) {
          await consulta.run(
            `INSERT INTO fotos (reporte_id, origen, url, clave, creado_en)
             VALUES (?, ?, ?, ?, ?)`,
            [filas[0].id, foto.origen, foto.url, foto.clave, ahora]
          );
        }
        await consulta.run('UPDATE reportes SET actualizado_en = ? WHERE folio = ?', [ahora, folio]);
      });
      return porFolio(folio);
    },
    async registrarEnvio({ reporteId, folio, destinatario, estado, error }) {
      const fecha = new Date().toISOString();
      await tx(async (consulta) => {
        await consulta.run(
          `INSERT INTO envios (reporte_id, folio, destinatario, fecha, estado, error)
           VALUES (?, ?, ?, ?, ?, ?)`,
          [reporteId, folio, destinatario, fecha, estado, error]
        );
      });
      return { fecha, estado, error: error || null, destinatario, folio };
    },
    async marcarEnviado(folio, iso) {
      await tx(async (consulta) => {
        await consulta.run(
          `UPDATE reportes
             SET estatus = 'enviado', enviado_en = ?, actualizado_en = ?
           WHERE folio = ?`,
          [iso, iso, folio]
        );
      });
      return porFolio(folio);
    },
  };
}

function cargarBetterSqlite() {
  try {
    return require('better-sqlite3');
  } catch (error) {
    return null;
  }
}

async function crearSqlite() {
  const Database = cargarBetterSqlite();
  if (!Database) {
    throw new Error('better-sqlite3 no está instalado. Usa DATA_BACKEND=json o instala las dependencias.');
  }
  const dir = directorioDatos();
  fs.mkdirSync(dir, { recursive: true });
  const archivo = path.join(dir, 'reportacalle.sqlite');
  const db = new Database(archivo);
  db.pragma('journal_mode = WAL');
  db.pragma('busy_timeout = 3000');
  const exclusivo = crearCola();
  const q = {
    async all(sql, params = []) {
      return db.prepare(sql).all(...params);
    },
    async run(sql, params = []) {
      db.prepare(sql).run(...params);
    },
  };
  const repo = crearRepositorioSql({
    motor: 'sqlite',
    exclusivo,
    q,
    tx: (fn) => exclusivo(async () => {
      db.exec('BEGIN IMMEDIATE');
      try {
        const salida = await fn(q);
        db.exec('COMMIT');
        return salida;
      } catch (error) {
        try { db.exec('ROLLBACK'); } catch (_) { /* ya estaba cerrada */ }
        throw error;
      }
    }),
    cerrar: async () => { db.close(); },
    asegurarTablas: async () => {
      db.exec(DDL_SQLITE);
      for (const sql of INDICES) db.exec(sql);
    },
  });
  await repo.preparar();
  return repo;
}

async function crearPostgres() {
  const { Pool } = require('pg');
  const connectionString = process.env.DATABASE_URL;
  const necesitaSsl = /supabase\.|sslmode=require/i.test(connectionString)
    && !/sslmode=disable/i.test(connectionString);
  const pool = new Pool({
    connectionString,
    ssl: necesitaSsl ? { rejectUnauthorized: false } : undefined,
  });
  const exclusivo = crearCola();
  const q = {
    async all(sql, params = []) {
      const resultado = await pool.query(aPg(sql), params);
      return resultado.rows;
    },
    async run(sql, params = []) {
      await pool.query(aPg(sql), params);
    },
  };
  const repo = crearRepositorioSql({
    motor: 'postgres',
    exclusivo,
    q,
    tx: (fn) => exclusivo(async () => {
      const cliente = await pool.connect();
      const consulta = {
        async all(sql, params = []) {
          const resultado = await cliente.query(aPg(sql), params);
          return resultado.rows;
        },
        async run(sql, params = []) {
          await cliente.query(aPg(sql), params);
        },
      };
      try {
        await cliente.query('BEGIN');
        const salida = await fn(consulta);
        await cliente.query('COMMIT');
        return salida;
      } catch (error) {
        try { await cliente.query('ROLLBACK'); } catch (_) { /* sin transacción activa */ }
        throw error;
      } finally {
        cliente.release();
      }
    }),
    cerrar: async () => { await pool.end(); },
    asegurarTablas: async () => {
      await pool.query(DDL_PG);
      for (const sql of INDICES) await pool.query(sql);
    },
  });
  await repo.preparar();
  return repo;
}

function crearJson() {
  const dir = directorioDatos();
  fs.mkdirSync(dir, { recursive: true });
  const archivo = path.join(dir, 'reportacalle.json');
  const vacio = () => ({ secuencia: 0, reportes: [], fotos: [], envios: [] });
  let estado = vacio();
  if (fs.existsSync(archivo)) {
    estado = JSON.parse(fs.readFileSync(archivo, 'utf8'));
    estado.reportes ||= [];
    estado.fotos ||= [];
    estado.envios ||= [];
    estado.secuencia ||= 0;
  }
  const exclusivo = crearCola();

  function guardar() {
    const tmp = `${archivo}.tmp`;
    fs.writeFileSync(tmp, JSON.stringify(estado, null, 2));
    fs.renameSync(tmp, archivo);
  }

  function siguienteId(lista) {
    return lista.reduce((max, item) => Math.max(max, item.id), 0) + 1;
  }

  function filasFiltradas(filtros) {
    return estado.reportes
      .filter((r) => !filtros.estatus || r.estatus === filtros.estatus)
      .filter((r) => !filtros.categoria || r.categoria === filtros.categoria)
      .slice()
      .sort((a, b) => b.id - a.id);
  }

  function armarFilas(filas) {
    return filas.map((fila) => presentar(
      fila,
      estado.fotos.filter((f) => f.reporte_id === fila.id).sort((a, b) => a.id - b.id),
      estado.envios.filter((e) => e.reporte_id === fila.id).sort((a, b) => a.id - b.id)
    ));
  }

  return {
    motor: 'json',
    async ping() {
      return Array.isArray(estado.reportes);
    },
    async cerrar() {},
    async crearReporte(datos, fotos) {
      return exclusivo(async () => {
        estado.secuencia += 1;
        const ahora = new Date().toISOString();
        const fila = {
          id: siguienteId(estado.reportes),
          folio: formatearFolio(estado.secuencia),
          categoria: datos.categoria,
          descripcion: datos.descripcion,
          lat: datos.lat,
          lng: datos.lng,
          anonimo: datos.anonimo ? 1 : 0,
          contacto_nombre: datos.contactoNombre,
          contacto_dato: datos.contactoDato,
          estatus: 'recibido',
          largo_cm: null,
          ancho_cm: null,
          profundidad_cm: null,
          area_cm2: null,
          recomendacion: null,
          enviado_en: null,
          creado_en: ahora,
          actualizado_en: ahora,
        };
        estado.reportes.push(fila);
        for (const foto of fotos) {
          estado.fotos.push({
            id: siguienteId(estado.fotos),
            reporte_id: fila.id,
            origen: foto.origen,
            url: foto.url,
            clave: foto.clave,
            creado_en: ahora,
          });
        }
        guardar();
        return armarFilas([fila])[0];
      });
    },
    async listar(filtros = {}) {
      return exclusivo(async () => armarFilas(filasFiltradas(filtros)));
    },
    async porFolio(folio) {
      return exclusivo(async () => {
        const fila = estado.reportes.find((r) => r.folio === folio);
        if (!fila) return null;
        return armarFilas([fila])[0];
      });
    },
    async actualizar(folio, campos) {
      return exclusivo(async () => {
        const fila = estado.reportes.find((r) => r.folio === folio);
        if (!fila) return null;
        fila.estatus = campos.estatus;
        fila.largo_cm = campos.largoCm;
        fila.ancho_cm = campos.anchoCm;
        fila.profundidad_cm = campos.profundidadCm;
        fila.area_cm2 = campos.areaCm2;
        fila.recomendacion = campos.recomendacion;
        fila.actualizado_en = new Date().toISOString();
        guardar();
        return armarFilas([fila])[0];
      });
    },
    async agregarFotos(folio, fotos) {
      return exclusivo(async () => {
        const fila = estado.reportes.find((r) => r.folio === folio);
        if (!fila) return null;
        const ahora = new Date().toISOString();
        for (const foto of fotos) {
          estado.fotos.push({
            id: siguienteId(estado.fotos),
            reporte_id: fila.id,
            origen: foto.origen,
            url: foto.url,
            clave: foto.clave,
            creado_en: ahora,
          });
        }
        fila.actualizado_en = ahora;
        guardar();
        return armarFilas([fila])[0];
      });
    },
    async registrarEnvio({ reporteId, folio, destinatario, estado: estadoEnvio, error }) {
      return exclusivo(async () => {
        const fecha = new Date().toISOString();
        estado.envios.push({
          id: siguienteId(estado.envios),
          reporte_id: reporteId,
          folio,
          destinatario,
          fecha,
          estado: estadoEnvio,
          error: error || null,
        });
        guardar();
        return { fecha, estado: estadoEnvio, error: error || null, destinatario, folio };
      });
    },
    async marcarEnviado(folio, iso) {
      return exclusivo(async () => {
        const fila = estado.reportes.find((r) => r.folio === folio);
        if (!fila) return null;
        fila.estatus = 'enviado';
        fila.enviado_en = iso;
        fila.actualizado_en = iso;
        guardar();
        return armarFilas([fila])[0];
      });
    },
  };
}

async function crearDatos() {
  const pedido = String(process.env.DATA_BACKEND || 'auto').trim().toLowerCase();
  const hayUrl = !esPendiente(process.env.DATABASE_URL);

  if (pedido === 'postgres' || (pedido === 'auto' && hayUrl)) {
    if (!hayUrl) throw new Error('DATA_BACKEND=postgres pero DATABASE_URL está vacía.');
    return crearPostgres();
  }
  if (pedido === 'json') return crearJson();
  if (pedido === 'sqlite') return crearSqlite();

  if (cargarBetterSqlite()) return crearSqlite();
  console.warn('SQLite no está disponible. Los datos se guardarán en un archivo JSON.');
  return crearJson();
}

